import React, { useState } from 'react';
import {
  Activity,
  ActivityType,
  ZoneSuitability,
} from '../types/planner';
import {
  X,
  CheckCircle2,
  Calendar,
  Clock,
  MapPin,
  ShieldCheck,
  AlertTriangle,
  Flame,
  Droplet,
  Copy,
  Check,
  Building2,
  Luggage,
  Sparkles,
} from 'lucide-react';
import { formatConditionLabel } from '../utils/weatherEngine';

interface WorkoutPlanModalProps {
  isOpen: boolean;
  onClose: () => void;
  suitability: ZoneSuitability;
  activity: Activity;
  activityType: ActivityType;
  durationMinutes: number;
}

export const WorkoutPlanModal: React.FC<WorkoutPlanModalProps> = ({
  isOpen,
  onClose,
  suitability,
  activity,
  activityType,
  durationMinutes,
}) => {
  const [copied, setCopied] = useState(false);
  const [checkedGear, setCheckedGear] = useState<Record<string, boolean>>({});

  if (!isOpen) return null;

  const { zone, isSafe, alerts, timeWindowSummary } = suitability;
  const totalCalories = Math.round((activity.estimatedCalPerHour * durationMinutes) / 60);
  const totalWater = Math.round((activity.waterRecommendedMlPerHour * durationMinutes) / 60);

  const toggleGear = (item: string) => {
    setCheckedGear((prev) => ({ ...prev, [item]: !prev[item] }));
  };

  const copyPlanToClipboard = () => {
    const text = `🇸🇬 SG EXERCISE PLAN · WEATHER VERIFIED\n` +
      `Activity: ${activity.name} (${activityType.toUpperCase()})\n` +
      `Location: ${zone.name} (${zone.region.toUpperCase()})\n` +
      `Time Window: ${timeWindowSummary.start} – ${timeWindowSummary.end} (${durationMinutes} mins)\n` +
      `Weather: ${formatConditionLabel(timeWindowSummary.conditionSummary)} · ${timeWindowSummary.avgTemp}°C\n` +
      `Rain Risk: ${suitability.maxRainProb}%\n` +
      `Lightning Alert: ${suitability.lightningAlertActive ? 'CAT 1 ALERT' : 'All Clear (Safe)'}\n` +
      `Air Quality: PSI ${suitability.psiValue} (${suitability.psiBand})\n` +
      `Estimated Burn: ~${totalCalories} kcal | Target Hydration: ${totalWater} ml\n` +
      `Indoor Backup: ${zone.indoorFacilities[0]?.name || 'ActiveSG Sports Hall'}\n` +
      `Generated by SG Exercise Weather Planner`;

    navigator.clipboard.writeText(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/60 backdrop-blur-sm animate-in fade-in duration-200">
      <div className="bg-white rounded-2xl border border-slate-200 shadow-2xl max-w-xl w-full max-h-[90vh] overflow-y-auto flex flex-col justify-between">
        {/* Modal Header */}
        <div className="p-5 sm:p-6 border-b border-slate-100 flex items-start justify-between gap-4">
          <div>
            <div className="flex items-center gap-2 text-xs font-semibold text-emerald-700 mb-1">
              <Sparkles className="w-3.5 h-3.5" />
              <span>Personalized Workout Itinerary</span>
            </div>
            <h2 className="text-xl font-bold text-slate-900">
              {activity.name} Session Plan
            </h2>
            <div className="flex items-center gap-2 text-xs text-slate-500 mt-1">
              <MapPin className="w-3.5 h-3.5 text-slate-400" />
              <span>{zone.name}</span>
              <span aria-hidden="true">·</span>
              <span>{durationMinutes} Minutes</span>
            </div>
          </div>

          <button
            onClick={onClose}
            className="p-1.5 rounded-lg text-slate-400 hover:text-slate-700 hover:bg-slate-100 transition-colors"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Modal Body */}
        <div className="p-5 sm:p-6 space-y-5 text-xs text-slate-700">
          {/* Safety Verification Badge */}
          <div
            className={`p-3.5 rounded-xl border flex items-start gap-3 ${
              isSafe || activityType === 'indoor'
                ? 'bg-emerald-50/80 border-emerald-200 text-emerald-950'
                : 'bg-rose-50/80 border-rose-200 text-rose-950'
            }`}
          >
            {isSafe || activityType === 'indoor' ? (
              <ShieldCheck className="w-5 h-5 text-emerald-600 shrink-0 mt-0.5" />
            ) : (
              <AlertTriangle className="w-5 h-5 text-rose-600 shrink-0 mt-0.5" />
            )}
            <div>
              <div className="font-bold text-sm">
                {activityType === 'indoor'
                  ? 'Weather-Proof Indoor Facility'
                  : isSafe
                  ? 'Weather Safety Clearance Granted'
                  : 'Weather Warning Detected'}
              </div>
              <p className="mt-0.5 text-xs leading-relaxed opacity-90">
                {suitability.recommendationNote}
              </p>
            </div>
          </div>

          {/* Schedule & Telemetry Card */}
          <div className="grid grid-cols-2 sm:grid-cols-4 gap-2.5 p-3.5 bg-slate-50 rounded-xl border border-slate-100 tabular-nums">
            <div>
              <div className="text-[11px] text-slate-500 mb-0.5 flex items-center gap-1">
                <Clock className="w-3 h-3 text-slate-400" />
                <span>Window</span>
              </div>
              <div className="font-bold text-slate-900 font-mono">
                {timeWindowSummary.start} – {timeWindowSummary.end}
              </div>
            </div>

            <div>
              <div className="text-[11px] text-slate-500 mb-0.5">Rain Risk</div>
              <div className="font-bold text-slate-900 font-mono">
                {suitability.maxRainProb}% {suitability.maxRainProb === 0 ? '(Nil)' : ''}
              </div>
            </div>

            <div>
              <div className="text-[11px] text-slate-500 mb-0.5">Lightning Alert</div>
              <div
                className={`font-bold font-mono ${
                  suitability.lightningAlertActive ? 'text-rose-600' : 'text-emerald-700'
                }`}
              >
                {suitability.lightningAlertActive ? 'Cat 1 Active' : 'All Clear'}
              </div>
            </div>

            <div>
              <div className="text-[11px] text-slate-500 mb-0.5">24h PSI</div>
              <div className="font-bold text-slate-900 font-mono">
                {suitability.psiValue} ({suitability.psiBand})
              </div>
            </div>
          </div>

          {/* Health & Performance Targets */}
          <div className="grid grid-cols-2 gap-3">
            <div className="p-3 bg-amber-50/50 rounded-lg border border-amber-100 flex items-center gap-2.5">
              <div className="p-2 rounded-md bg-amber-100 text-amber-800">
                <Flame className="w-4 h-4" />
              </div>
              <div>
                <div className="text-[11px] text-slate-500 font-medium">Estimated Calorie Burn</div>
                <div className="text-sm font-bold text-amber-950 font-mono">
                  ~{totalCalories} kcal
                </div>
              </div>
            </div>

            <div className="p-3 bg-blue-50/50 rounded-lg border border-blue-100 flex items-center gap-2.5">
              <div className="p-2 rounded-md bg-blue-100 text-blue-800">
                <Droplet className="w-4 h-4" />
              </div>
              <div>
                <div className="text-[11px] text-slate-500 font-medium">Recommended Water</div>
                <div className="text-sm font-bold text-blue-950 font-mono">
                  {totalWater} ml
                </div>
              </div>
            </div>
          </div>

          {/* Gear & Prep Checklist */}
          <div>
            <div className="flex items-center justify-between mb-2">
              <label className="text-xs font-semibold uppercase tracking-wider text-slate-500 flex items-center gap-1.5">
                <Luggage className="w-3.5 h-3.5 text-slate-400" />
                <span>Recommended Gear Checklist</span>
              </label>
              <span className="text-[11px] text-slate-400">Tap to check off</span>
            </div>

            <div className="grid grid-cols-1 sm:grid-cols-2 gap-2">
              {activity.recommendedGear.map((gear, idx) => {
                const isChecked = !!checkedGear[gear];
                return (
                  <button
                    key={idx}
                    type="button"
                    onClick={() => toggleGear(gear)}
                    className={`p-2 rounded-lg border text-left flex items-center gap-2 transition-all ${
                      isChecked
                        ? 'bg-emerald-50/80 border-emerald-300 text-emerald-900 line-through'
                        : 'bg-white border-slate-200 text-slate-700 hover:bg-slate-50'
                    }`}
                  >
                    <div
                      className={`w-4 h-4 rounded border flex items-center justify-center shrink-0 ${
                        isChecked
                          ? 'bg-emerald-600 border-emerald-600 text-white'
                          : 'border-slate-300 bg-white'
                      }`}
                    >
                      {isChecked && <Check className="w-3 h-3 stroke-[3]" />}
                    </div>
                    <span className="text-xs truncate">{gear}</span>
                  </button>
                );
              })}
            </div>
          </div>

          {/* Indoor Plan B Backup Option */}
          <div className="p-3.5 rounded-xl bg-slate-50 border border-slate-200/80">
            <div className="flex items-center gap-1.5 font-semibold text-slate-900 mb-1">
              <Building2 className="w-4 h-4 text-emerald-600" />
              <span>Singapore Weather Plan B Backup</span>
            </div>
            <p className="text-xs text-slate-600 leading-relaxed">
              If an unexpected tropical convective shower or NEA lightning alert develops, immediately transition to{' '}
              <strong className="text-slate-900">{zone.indoorFacilities[0]?.name}</strong> ({zone.indoorFacilities[0]?.address}), located directly adjacent with full rain shelter.
            </p>
          </div>
        </div>

        {/* Modal Footer */}
        <div className="p-4 sm:p-5 bg-slate-50 border-t border-slate-100 flex items-center justify-between gap-3">
          <button
            type="button"
            onClick={copyPlanToClipboard}
            className="px-4 py-2 text-xs font-semibold rounded-lg border border-slate-200 bg-white text-slate-700 hover:bg-slate-100 transition-colors flex items-center gap-1.5 shadow-xs"
          >
            {copied ? (
              <>
                <Check className="w-3.5 h-3.5 text-emerald-600" />
                <span className="text-emerald-700 font-bold">Copied to Clipboard!</span>
              </>
            ) : (
              <>
                <Copy className="w-3.5 h-3.5 text-slate-500" />
                <span>Copy Plan Summary</span>
              </>
            )}
          </button>

          <button
            type="button"
            onClick={onClose}
            className="px-5 py-2 text-xs font-semibold rounded-lg bg-slate-900 text-white hover:bg-slate-800 transition-colors shadow-sm"
          >
            Done
          </button>
        </div>
      </div>
    </div>
  );
};
